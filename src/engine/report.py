"""Render reports/v25/EVALUATION_REPORT.md from the saved JSON results (no hand-typed numbers).

Run order:  python -m src.engine.tune ; python -m src.engine.select ; python -m src.engine.final_eval ;
            python -m src.engine.report
"""
from __future__ import annotations

import json

from src.config import REPORTS_DIR

D = REPORTS_DIR / "v25"


def _load(name: str) -> dict:
    return json.loads((D / name).read_text(encoding="utf-8"))


def _row(name: str, m: dict) -> str:
    return (f"| {name} | {m['accuracy']*100:.1f}% | {m['log_loss']:.4f} | {m['brier']:.4f} | {m['rps']:.4f} | "
            f"{m['macro_f1']:.3f} | {m['draw_recall']*100:.1f}% | {m['ece_draw']:.3f} |")


def render() -> str:
    tune, sel, test = _load("tuning_results.json"), _load("selection.json"), _load("test_results.json")
    L: list[str] = []
    L += ["# PitchIQ v2.5 - Evaluation Report", "",
          "Generated by `python -m src.engine.report` from `tuning_results.json`, `selection.json` and "
          "`test_results.json`. All figures are out-of-sample, produced by rolling-origin (expanding-window) "
          "backtesting. Lower is better for log loss, Brier and RPS.", "",
          "## 1. Protocol", "",
          "| Window | Seasons | Used for |", "|---|---|---|",
          f"| Warm-up | 2015-16 | initialises ratings only; excluded from training and scoring |",
          f"| Tuning | {', '.join(tune['window'])} | hyper-parameters and feature-group selection |",
          "| Selection | 2022-23, 2023-24 | ensemble recipe and calibration decision (nested season swap) |",
          f"| **Final test** | {', '.join(test['test_seasons'])} ({test['n_matches']} matches) | scored once after everything was frozen |", "",
          "Caveat: the test window is the same one v2.4 reported on, so that window is not pristine with respect to "
          "v2.4 development. v2.5 itself never used it for any decision.", ""]

    L += ["## 2. Final test results", "",
          "| Model | Accuracy | Log loss | Brier | RPS | Macro-F1 | Draw recall | Draw ECE |", "|---|---|---|---|---|---|---|---|"]
    for name, m in test["metrics"].items():
        if name.startswith("Always-home"):
            continue
        L.append(_row(name.replace("  <- production recipe", " **(production)**"), m))
    lo, hi = test["accuracy_ci95_ensemble"]
    lo4, hi4 = test["accuracy_ci95_v24"]
    L += ["", f"Accuracy 95% bootstrap interval at n={test['n_matches']}: v2.5 {lo*100:.1f}%-{hi*100:.1f}%, "
          f"v2.4 {lo4*100:.1f}%-{hi4*100:.1f}%. Always-home accuracy is "
          f"{test['metrics']['Always-home (accuracy reference)']['accuracy']*100:.1f}%.", "",
          "### Paired comparison with v2.4 (per-match log loss, negative = v2.5 better)", "",
          "| Comparison | Mean difference | 95% CI | P(v2.5 better) |", "|---|---|---|---|"]
    for k, v in test["paired_vs_v24"].items():
        L.append(f"| {k} | {v['mean_diff']:+.4f} | [{v['ci95_low']:+.4f}, {v['ci95_high']:+.4f}] | {v['prob_a_better']*100:.1f}% |")
    L += ["", "Interpretation: the interval includes zero in every comparison, so the improvement is "
          "directionally consistent but **not statistically conclusive** at this sample size. The bootstrap resamples "
          "matches independently and ignores matchweek dependence, so treat the interval as indicative.", ""]

    L += ["### Per season", "", "| Season | Model | Accuracy | Log loss | Brier |", "|---|---|---|---|---|"]
    for season, models in test["per_season"].items():
        for name, m in models.items():
            L.append(f"| {season} | {name.replace('  <- production recipe', '')} | {m['accuracy']*100:.1f}% | {m['log_loss']:.4f} | {m['brier']:.4f} |")

    d = test["draw_diagnostics"]
    L += ["", "## 3. Draws", "",
          "Neither v2.4 nor v2.5 can separate draws. Under argmax, draw recall is ~0% because P(draw) never "
          "becomes the largest class probability; v2.5's maximum P(draw) on the test set is "
          f"{d['max_p_draw']:.3f}. Mean P(draw) is {d['mean_p_draw_when_draw']:.3f} on matches that were draws vs "
          f"{d['mean_p_draw_when_not_draw']:.3f} on matches that were not (v2.4: {d['v24_mean_p_draw_when_draw']:.3f} vs "
          f"{d['v24_mean_p_draw_when_not_draw']:.3f}). The observed draw rate was "
          f"{test['metrics'][next(k for k in test['metrics'] if 'production' in k)]['observed_draw_rate']*100:.1f}%, versus a mean predicted "
          f"{test['metrics'][next(k for k in test['metrics'] if 'production' in k)]['mean_p_draw']*100:.1f}%. "
          "No probability was inflated to force draw predictions: doing so would damage log loss and calibration "
          "without adding real information. Draw recall is therefore reported, but it is not a target.", ""]

    L += ["## 4. Calibration (v2.5 ensemble, equal-count bins)", ""]
    for cls, rows in test["reliability"].items():
        L += [f"**{cls.title()}**", "", "| n | mean predicted | observed |", "|---|---|---|"]
        L += [f"| {r['n']} | {r['mean_predicted']:.3f} | {r['observed_frequency']:.3f} |" for r in rows]
        L.append("")
    L += [f"Temperature scaling was evaluated on the selection window and **not applied** "
          f"(nested gain {sel['temperature']['nested_mean_gain']:+.4f}, fitted T={sel['temperature']['fitted_T']:.2f}).", ""]

    L += ["## 5. Tuning window summary", "",
          f"Climatology log loss {tune['climatology']:.4f}; Elo-only logistic {tune['elo_only_lr']:.4f}.", "",
          "| Family | Best configuration | Tuning log loss |", "|---|---|---|",
          f"| Logistic (all features) | C={tune['lr_best']['C']}, half-life={tune['lr_best']['half_life']} | {tune['lr_best']['log_loss']:.4f} |",
          f"| Logistic (core: {', '.join(tune['lr_core']['groups'])}) | C={tune['lr_core']['best']['C']} | {tune['lr_core']['best']['log_loss']:.4f} |",
          f"| Random forest | depth={tune['rf_best']['max_depth']}, leaf={tune['rf_best']['min_samples_leaf']} | {tune['rf_best']['log_loss']:.4f} |",
          f"| XGBoost | depth={tune['xgb_best']['max_depth']}, trees={tune['xgb_best']['n_estimators']} | {tune['xgb_best']['log_loss']:.4f} |",
          f"| Separate home/away Poisson | alpha={tune['goal_best']['alpha']}, half-life={tune['goal_best']['half_life']} | {tune['goal_best']['log_loss']:.4f} |",
          f"| Dixon-Coles | half-life={tune['dc_best']['half_life_days']}d, ridge={tune['dc_best']['ridge']} | {tune['dc_best']['log_loss']:.4f} |", "",
          "### Feature-group ablation (logistic, tuning window)", "", "| Variant | Log loss |", "|---|---|"]
    for k, v in tune["lr_ablation"].items():
        L.append(f"| {k} | {v:.4f} |")
    L += ["", "Finding: team-strength ratings carry nearly all the usable signal. Adding rolling form, shots, schedule and "
          "head-to-head groups does not improve out-of-sample log loss; strongly regularised models (or ensembles) "
          "are needed to keep them from hurting.", ""]

    L += ["## 6. Selection window", "", "| Method | Nested season-swap log loss |", "|---|---|"]
    for k, v in sel["nested_season_swap_log_loss"].items():
        L.append(f"| {k} | {v:.4f} |")
    L += ["", f"Chosen: **{sel['chosen_method']}**. Selection-window single-model log loss:", "", "| Model | Log loss |", "|---|---|"]
    for k, v in sel["single_models"].items():
        L.append(f"| {k} | {v['log_loss']:.4f} |")
    L += ["", "Observation (not acted on): on the test window the single `goal_poisson` model scored better than the "
          "ensemble. Switching to it now would be tuning on the test set, so the pre-registered equal-weight ensemble "
          "stays the production recipe.", ""]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    path = D / "EVALUATION_REPORT.md"
    path.write_text(render(), encoding="utf-8")
    print("wrote", path)
